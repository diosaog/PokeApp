// Local design preview (Phase27B). NOT part of the product bundle or deployment.
//
//   npm run preview:design   ->  http://127.0.0.1:4173
//
// Serves the built web (dist-preview/) and a SYNTHETIC API on 127.0.0.1:4174 that
// reuses the Playwright e2e fixture (e2e/fixtures.ts): fictional trainers and
// Pokémon, no account, no network, nothing persisted. Any trainer name and PIN
// enters. A fixed banner on every page says it is a preview with demo data.
import { createServer } from "node:http";
import { readFile, stat } from "node:fs/promises";
import { extname, join, normalize, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { fixture } from "../e2e/fixtures.ts";

const WEB_PORT = 4173,
  API_PORT = 4174,
  HOST = "127.0.0.1";
const root = resolve(
  fileURLToPath(new URL("../dist-preview/", import.meta.url)),
);
const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript",
  ".css": "text/css",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".json": "application/json",
  ".woff2": "font/woff2",
};
// The banner is styled by its own same-origin sheet: the production CSP below
// (style-src 'self') forbids inline styles.
const banner = `<link rel="stylesheet" href="/__preview/banner.css"><div id="preview-banner" role="note">VISTA PREVIA LOCAL · datos sintéticos de demostración · nada se guarda</div>`;
const bannerCss = `#preview-banner{position:fixed;z-index:2147483647;left:50%;bottom:10px;transform:translateX(-50%);padding:6px 14px;border-radius:999px;background:#06131d;color:#a9f6ea;border:1px solid #2de2c8;font:600 12px/1.4 'Segoe UI',system-ui,sans-serif;pointer-events:none;box-shadow:0 6px 18px #0008}`;
// The same delivery headers as production (dist-preview/_headers, generated by
// vite.config.ts): the browser itself then allows connections only to 'self'
// and the synthetic API origin baked into the preview build.
const delivery = Object.fromEntries(
  (await readFile(join(root, "_headers"), "utf8"))
    .split("\n")
    .map((line) => /^\s+([\w-]+):\s*(.+)$/.exec(line))
    .filter(Boolean)
    .map((m) => [m[1], m[2].trim()]),
);
if (
  !/connect-src 'self' http:\/\/127\.0\.0\.1:4174;/.test(
    delivery["Content-Security-Policy"] || "",
  )
)
  throw new Error("dist-preview must be built for the synthetic API (run.mjs)");

// Loopback only, also by name: a page elsewhere cannot reach these servers
// through DNS rebinding (Host) or read the API cross-site (Origin).
const loopback = (value, port) =>
  value === `${HOST}:${port}` || value === `localhost:${port}`;
const allowedOrigin = (origin) =>
  !origin || /^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(origin);

// The fixture talks to Playwright's page.route(); adapt it to plain HTTP.
let handler;
await fixture(
  { route: async (_pattern, fn) => (handler = fn) },
  false,
  `http://${HOST}:${API_PORT}`,
);

createServer(async (req, res) => {
  if (
    !loopback(req.headers.host, API_PORT) ||
    !allowedOrigin(req.headers.origin)
  )
    return res.writeHead(403).end();
  const chunks = [];
  for await (const chunk of req) chunks.push(chunk);
  const body = Buffer.concat(chunks).toString("utf8");
  const headers = Object.fromEntries(
    Object.entries(req.headers).map(([k, v]) => [k.toLowerCase(), String(v)]),
  );
  const request = {
    url: () => `http://${HOST}:${API_PORT}${req.url}`,
    method: () => req.method,
    headers: () => headers,
    postDataJSON: () => (body ? JSON.parse(body) : null),
  };
  try {
    await handler({
      request: () => request,
      fulfill: async ({ status = 200, headers: extra = {}, json }) => {
        res.writeHead(status, {
          ...extra,
          ...(json === undefined ? {} : { "content-type": "application/json" }),
        });
        res.end(json === undefined ? "" : JSON.stringify(json));
      },
    });
  } catch {
    // A malformed request must not take the preview down.
    if (!res.headersSent) res.writeHead(400);
    res.end();
  }
}).listen(API_PORT, HOST);

createServer(async (req, res) => {
  if (!loopback(req.headers.host, WEB_PORT)) return res.writeHead(403).end();
  let path;
  try {
    path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname));
  } catch {
    return res.writeHead(400).end(); // malformed escape, e.g. "/%E0"
  }
  if (path === join("/__preview", "banner.css")) {
    res.writeHead(200, { ...delivery, "content-type": types[".css"] });
    return res.end(bannerCss);
  }
  let file = join(root, path);
  if (!file.startsWith(root)) return res.writeHead(403).end();
  try {
    if (!(await stat(file)).isFile()) throw new Error("dir");
  } catch {
    file = join(root, "index.html"); // SPA routes
  }
  let data = await readFile(file);
  if (file.endsWith("index.html"))
    data = Buffer.from(
      data.toString("utf8").replace("</body>", banner + "</body>"),
    );
  res.writeHead(200, {
    ...delivery,
    "content-type": types[extname(file)] || "application/octet-stream",
    "cache-control": "no-store",
  });
  res.end(data);
}).listen(WEB_PORT, HOST);

console.log(
  `PokeApp design preview: http://${HOST}:${WEB_PORT}  (synthetic data)`,
);
